async def debug_info():
    """Diagnostic endpoint to check app state."""
    import glob
    app_dir = os.path.dirname(os.path.abspath(__file__))
    local_files = glob.glob(os.path.join(app_dir, "*"))
    return {
        "ppt_store_summaries": len(ppt_store["summaries"]),
        "ppt_store_data": len(ppt_store["ppt_data"]),
        "topic_names": _get_topic_names(),
        "volume_path": PPT_VOLUME_PATH,
        "volume_accessible": os.path.isdir(PPT_VOLUME_PATH) if PPT_VOLUME_PATH else False,
        "app_dir": app_dir,
        "local_files": [os.path.basename(f) for f in local_files],
        "local_cache_exists": os.path.exists(os.path.join(app_dir, "ppt_cache.json")),
    }


@app.post("/api/chat")
async def chat(request: ChatRequest):
    """Full chat endpoint with history and optional SSE streaming."""
    # Extract the latest user message for RAG routing
    user_messages = [m for m in request.messages if m.role == "user"]
    if not user_messages:
        raise HTTPException(status_code=400, detail="No user message provided")
    query = user_messages[-1].content

    try:
        if request.stream:
            def event_generator():
                response = _rag_query(
                    query,
                    stream=True,
                    temperature=request.temperature,
                    max_tokens=request.max_tokens,
                )
                for chunk in response:
                    if chunk.choices and chunk.choices[0].delta.content:
                        data = json.dumps({"content": chunk.choices[0].delta.content})
                        yield f"data: {data}\n\n"
                yield "data: [DONE]\n\n"

            return StreamingResponse(
                event_generator(),
                media_type="text/event-stream",
                headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"},
            )
        else:
            response = _rag_query(
                query,
                stream=False,
                temperature=request.temperature,
                max_tokens=request.max_tokens,
            )
            return {
                "content": response.choices[0].message.content,
                "usage": {
                    "prompt_tokens": response.usage.prompt_tokens,
                    "completion_tokens": response.usage.completion_tokens,
                    "total_tokens": response.usage.total_tokens,
                },
            }
    except Exception as e:
        logger.exception("Error in /api/chat")
        raise HTTPException(status_code=500, detail=str(e))


@app.post("/api/chat/simple")
async def chat_simple(message: dict):
    """Simple endpoint — accepts {"message": "..."}."""
    user_msg = message.get("message", "")
    if not user_msg:
        raise HTTPException(status_code=400, detail="'message' field is required")

    try:
        response = _rag_query(user_msg)
        return {"response": response.choices[0].message.content}
    except Exception as e:
        logger.exception("Error in /api/chat/simple")
        raise HTTPException(status_code=500, detail=str(e))


if __name__ == "__main__":
    import uvicorn
    uvicorn.run(app, host="0.0.0.0", port=8000)
