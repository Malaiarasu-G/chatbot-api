import os
import json
import logging
from typing import List, Optional
from contextlib import asynccontextmanager

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import StreamingResponse
from pydantic import BaseModel
from openai import AzureOpenAI
from dotenv import load_dotenv

from ppt_cache import load_cache
from rag_engine import (
    find_relevant_ppts,
    generate_answer,
    generate_no_context_answer,
    generate_greeting_response,
)

# ── Logging ─────────────────────────────────────────────────────────
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s  %(levelname)-8s  %(name)s  %(message)s",
)
logger = logging.getLogger(__name__)

# ── Load environment variables ──────────────────────────────────────
load_dotenv()

AZURE_ENDPOINT = os.getenv("AZURE_OPENAI_ENDPOINT")
DEPLOYMENT_NAME = os.getenv("AZURE_OPENAI_DEPLOYMENT")
API_VERSION = os.getenv("AZURE_OPENAI_API_VERSION")
API_KEY = os.getenv("AZURE_OPENAI_API_KEY")
PPT_VOLUME_PATH = os.getenv(
    "PPT_VOLUME_PATH",
    "/Volumes/integrated_intelligence_poc/default/kiip_docs/ppts",
)

client = AzureOpenAI(
    azure_endpoint=AZURE_ENDPOINT,
    api_key=API_KEY,
    api_version=API_VERSION,
)

# ── In-memory PPT store (populated on startup) ─────────────────────
ppt_store: dict = {
    "summaries": [],   # [{filename, summary}, ...]
    "ppt_data": [],    # [{filename, file_path, total_slides, slides}, ...]
}

# ── Greeting detection ────────────────────────────────────────────
_GREETINGS = {
    "hi", "hello", "hey", "good morning", "good afternoon",
    "good evening", "howdy", "greetings", "sup", "yo", "hola",
    "thanks", "thank you", "bye", "goodbye",
}


def _is_greeting(query: str) -> bool:
    """Return True for simple conversational inputs."""
    cleaned = query.strip().lower().rstrip("!.,?")
    return cleaned in _GREETINGS


def _get_topic_names() -> list:
    """Derive human-friendly topic names from loaded PPT filenames."""
    return [
        s["filename"].replace(".pptx", "").replace(".ppt", "")
        for s in ppt_store["summaries"]
    ]


def initialize_ppt_data():
    """Load pre-computed PPT cache (generated by preprocess_ppts notebook)."""
    global ppt_store
    logger.info("Loading PPT cache ...")

    cache = load_cache(PPT_VOLUME_PATH)
    if cache:
        ppt_store["summaries"] = cache.get("summaries", [])
        ppt_store["ppt_data"] = cache.get("ppt_data", [])
        logger.info(
            "PPT data loaded — %d presentations ready.",
            len(ppt_store["ppt_data"]),
        )
    else:
        logger.error(
            "No PPT cache found! Run the preprocess_ppts notebook first "
            "to generate ppt_cache.json in the app directory."
        )


# ── FastAPI App with lifespan ───────────────────────────────────────
@asynccontextmanager
async def lifespan(app):
    try:
        initialize_ppt_data()
    except Exception:
        logger.exception("PPT initialization failed — app will start without PPT data.")
    yield


app = FastAPI(title="Chatbot API", lifespan=lifespan)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


# ── Models ──────────────────────────────────────────────────────────
class Message(BaseModel):
    role: str
    content: str


class ChatRequest(BaseModel):
    messages: List[Message]
    stream: Optional[bool] = False
    temperature: Optional[float] = 0.7
    max_tokens: Optional[int] = 1024


# ── Helper: run the two-stage RAG pipeline ────────────────────────
def _rag_query(
    query: str,
    *,
    stream: bool = False,
    temperature: float = 0.7,
    max_tokens: int = 1024,
):
    """Route the query to relevant PPTs and return the LLM response."""
    topic_names = _get_topic_names()

    # Handle greetings / small-talk
    if _is_greeting(query):
        logger.info("Greeting detected — returning topic list.")
        return generate_greeting_response(
            client,
            DEPLOYMENT_NAME,
            query,
            topic_names,
            stream=stream,
            temperature=temperature,
            max_tokens=max_tokens,
        )

    # Stage 1 — find relevant PPTs
    relevant_names = find_relevant_ppts(
        client, DEPLOYMENT_NAME, query, ppt_store["summaries"]
    )
    logger.info("Query routed to PPTs: %s", relevant_names)

    # Stage 2 — generate grounded answer
    if relevant_names:
        matched = [
            p for p in ppt_store["ppt_data"] if p["filename"] in relevant_names
        ]
        return generate_answer(
            client,
            DEPLOYMENT_NAME,
            query,
            matched,
            stream=stream,
            temperature=temperature,
            max_tokens=max_tokens,
        )
    else:
        return generate_no_context_answer(
            client,
            DEPLOYMENT_NAME,
            query,
            topic_names,
            stream=stream,
            temperature=temperature,
            max_tokens=max_tokens,
        )


# ── Endpoints ───────────────────────────────────────────────────────
@app.get("/health")
async def health_check():
    return {
        "status": "ok",
        "model": DEPLOYMENT_NAME,
        "presentations_loaded": len(ppt_store["ppt_data"]),
        "topics": _get_topic_names(),
    }


